// Shuffle array helper
function shuffleArray<T>(array: T[]): T[] {
  const shuffled = [...array]
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }
  return shuffled
}

// Get questions for a topic, shuffled with shuffled options
export function getQuestionsForTopic(topicId: string, count: number = 10): Question[] {
  const topic = topics.find(t => t.id === topicId)
  if (!topic) return []
  
  // Shuffle questions
  const shuffledQuestions = shuffleArray(topic.questions)
  
  // For each question, shuffle the options
  const questionsWithShuffledOptions = shuffledQuestions.map(q => ({
    ...q,
    options: q.options ? shuffleArray(q.options) : undefined
  }))
  
  return questionsWithShuffledOptions.slice(0, Math.min(count, questionsWithShuffledOptions.length))
}

// Get topic by ID
export function getTopicById(topicId: string): Topic | undefined {
  return topics.find(t => t.id === topicId)
}
